using System.Collections.Generic;
using System.Text;
using SystemVerilogCore.Documents;

namespace pluginVerilog.CoreBridge
{
    /// <summary>
    /// Exposes the parser's UI-free element labels to a host that can only
    /// render markdown (the language server), plus the palette those labels
    /// refer to.
    ///
    /// <para>
    /// The desktop editor paints a mouse-over hint by turning the label's runs
    /// into a <c>ColorLabel</c> (see <c>ToPopupItem</c>). A markdown host has
    /// no such primitive: VS Code's hover sanitizer strips <c>style</c> /
    /// <c>class</c>, so the colours can only come from a fenced code block that
    /// is tokenised by a TextMate grammar. This adapter supplies both halves -
    /// the label as text (through <see cref="VerilogLabelRuns"/>) and the
    /// palette the host needs to declare a matching grammar - so the server
    /// never has to know about the parser's element types.
    /// </para>
    /// </summary>
    public static class ElementLabelAdapter
    {
        /// <summary>
        /// The TextMate language id the labels are rendered with.
        ///
        /// <para>
        /// The extension contributes this id with the grammar generated by
        /// <see cref="HoverGrammar"/> (same colours as the parser palette). It
        /// is a dedicated id so the grammar only ever affects hover code
        /// blocks and never the editor's own highlighting.
        /// </para>
        /// </summary>
        public const string LabelLanguage = "systemverilog-hover";

        /// <summary>
        /// Builds the coloured-markdown rendering of an element's declaration
        /// label (the same label the editor's hint shows).
        /// </summary>
        /// <returns>
        /// A fenced code block, or null when the element has no label (the
        /// caller then falls back to a plain description).
        /// </returns>
        public static string? BuildLabelMarkdown(Verilog.INamedElement? element)
        {
            VerilogLabel? label = BuildLabel(element);
            if (label == null) return null;
            return VerilogLabelRuns.ToFencedCodeBlock(label, LabelLanguage);
        }

        /// <summary>
        /// The plain signature the editor's hint would show, for elements that
        /// have no label of their own (building blocks). Rendered in the same
        /// fence as the labels so every hover is coloured the same way.
        /// </summary>
        /// <returns>The fenced block, or null when the element has no name.</returns>
        public static string? BuildSignatureMarkdown(ISystemVerilogNamedElement? element)
        {
            if (element == null) return null;
            if (string.IsNullOrEmpty(element.Name)) return null;

            return VerilogLabelRuns.ToFencedCodeBlock(
                HoverContent.BuildSignature(element), LabelLanguage);
        }

        /// <summary>
        /// The label the editor's mouse-over hint renders for this element, or
        /// null when the element type has no label.
        /// </summary>
        public static VerilogLabel? BuildLabel(Verilog.INamedElement? element)
        {
            if (element == null) return null;

            // Mirrors ParsedDocument.GetPopupItem: only these element kinds
            // carry a hint label in the editor.
            try
            {
                VerilogLabel label = new();
                switch (element)
                {
                    case Verilog.DataObjects.DataObject dataObject:
                        dataObject.AppendLabel(label);
                        return label;
                    case Verilog.Function function:
                        function.AppendLabel(label);
                        return label;
                    case Verilog.Task_ task:
                        task.AppendLabel(label);
                        return label;
                    case Verilog.DataObjects.Typedef typedef:
                        typedef.AppendLabel(label);
                        return label;
                    default:
                        return null;
                }
            }
            catch
            {
                // A hint must never fail the hover request: an unresolved
                // cross-project element can throw while describing itself.
                return null;
            }
        }

        /// <summary>
        /// The palette slots the labels use, keyed by the contract's palette
        /// index, as <c>#RRGGBB</c>. A host declares a TextMate grammar with
        /// these colours so the fenced label matches the desktop editor.
        /// </summary>
        public static Dictionary<string, string> GetPalette()
        {
            Dictionary<string, string> palette = new();
            CodeDrawStyle style = new();

            foreach (VerilogColorType colorType in EnumeratePaletteSlots())
            {
                Avalonia.Media.Color color =
                    style.Color((CodeDrawStyle.ColorType)(byte)colorType);
                palette[colorType.ToString()] = ToHex(color);
            }
            return palette;
        }

        /// <summary>
        /// The palette slots the parser can attach to a label run. The editor
        /// palette holds 16 slots but only these are used by labels; the rest
        /// are unused placeholders.
        /// </summary>
        private static IEnumerable<VerilogColorType> EnumeratePaletteSlots()
        {
            yield return VerilogColorType.Normal;
            yield return VerilogColorType.Inactivated;
            yield return VerilogColorType.Register;
            yield return VerilogColorType.Keyword;
            yield return VerilogColorType.Comment;
            yield return VerilogColorType.Identifier;
            yield return VerilogColorType.Parameter;
            yield return VerilogColorType.Number;
            yield return VerilogColorType.Net;
            yield return VerilogColorType.HighLightedComment;
            yield return VerilogColorType.Variable;
            yield return VerilogColorType.CommentAnnotation;
        }

        private static string ToHex(Avalonia.Media.Color color) =>
            $"#{color.R:X2}{color.G:X2}{color.B:X2}";
    }
}
